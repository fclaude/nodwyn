#!/usr/bin/env python3
"""Writes internal/frontend/web/licenses/go-modules.txt: the licence of every
Go module linked into the nodwyn binary, which `nodwyn licenses` prints.

A binary that carries other people's code carries their notices (MIT, BSD and
Apache 2.0 all ask for it). The set is what `go list -deps` finds for the
command on the platforms nodwyn is built for, with and without the webview tag,
so a library that only one build links is not missed. Run it when go.mod
changes; TestEveryModuleHasANotice fails until it has been.

    python3 scripts/licenses.py          # rewrite the file
    python3 scripts/licenses.py --check  # fail if the file is out of date
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "internal", "frontend", "web", "licenses", "go-modules.txt")
NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING", "COPYING.txt", "NOTICE", "NOTICE.md", "NOTICE.txt")


def linked():
    """The (path, version, dir) of every module linked on some platform."""
    found = {}
    for goos in ("linux", "darwin", "windows"):
        for tags in ("", "webview"):
            env = dict(os.environ, GOOS=goos, CGO_ENABLED="1" if goos == "linux" else "0")
            fmt = "{{if .Module}}{{if not .Module.Main}}{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}{{end}}{{end}}"
            run = subprocess.run(["go", "list", "-deps", "-tags", tags, "-f", fmt, "./cmd/nodwyn"], cwd=ROOT, env=env, capture_output=True, text=True)
            if run.returncode != 0:
                sys.exit(f"go list ({goos}, tags {tags!r}) failed:\n{run.stderr}")
            for line in run.stdout.splitlines():
                parts = line.split(" ", 2)
                if len(parts) == 3:
                    found[parts[0]] = (parts[1], parts[2])
    return sorted((path, v, d) for path, (v, d) in found.items())


def render():
    out = [
        "The Go libraries linked into this binary, with the licence each is under.",
        "Generated by scripts/licenses.py from the modules `go list -deps` finds.",
    ]
    for path, version, directory in linked():
        if not directory or not os.path.isdir(directory):
            sys.exit(f"{path} {version} is not in the module cache: run `go mod download` and try again")
        texts = []
        for name in NAMES:
            file = os.path.join(directory, name)
            if os.path.isfile(file):
                with open(file, encoding="utf-8", errors="replace") as f:
                    texts.append(f.read().strip("\n"))
        if not texts:
            sys.exit(f"{path} {version} has no licence file")
        out.append(f"\n\nGo library: {path} {version}\n\n" + "\n\n".join(texts))
    return "\n".join(out) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit(f"{OUT} is out of date: run python3 scripts/licenses.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
