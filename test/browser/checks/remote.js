const { chromium } = require("playwright");
const { spawn, execSync } = require("child_process");
const fs = require("fs");
const out = process.argv[2];
(async () => {
  const root = fs.mkdtempSync("/tmp/nodwyn-remote-");
  for (const d of ["config/nodwyn", "data", "run", "work"]) fs.mkdirSync(`${root}/${d}`, { recursive: true, mode: 0o700 });
  fs.writeFileSync(`${root}/work/app.js`, 'function sessionRow(session) {\n  const row = node("button", "", "session");\n  row.append(node("span", session.first, "title"));\n  row.append(node("span", session.repo, "meta"));\n  return row;\n}\n');
  const kids = [];
  process.on("exit", () => kids.forEach((k) => k.kill("SIGKILL")));
  const env = { ...process.env, XDG_CONFIG_HOME: `${root}/config`, XDG_DATA_HOME: `${root}/data`, XDG_RUNTIME_DIR: `${root}/run` };
  const line = (proc, re, stream) => new Promise((resolve) => { let b = ""; proc[stream].on("data", (d) => { b += d; const m = re.exec(b); if (m) resolve(m[1]); }); });
  const model = spawn(process.env.DEMO, ["-model-only"]); kids.push(model);
  const modelURL = await line(model, /MODEL (\S+)/, "stdout");
  fs.writeFileSync(`${root}/config/nodwyn/config.toml`, `[control]\nurl = "${modelURL}"\nmodel = "demo"\n`);
  const daemon = spawn(process.env.NODWYN, ["daemon", "--no-keychain"], { env }); kids.push(daemon);
  await line(daemon, /(listening)/, "stderr");
  const port = 17000 + Math.floor(Math.random() * 1000);
  const ui = spawn(process.env.NODWYN, ["ui", "--listen", `127.0.0.1:${port}`, "--name", `desk.test:${port}`, "--no-open"], { env }); kids.push(ui);
  const code = await line(ui, /Pairing code[^:]*: (\S+)/, "stderr");
  const browser = await chromium.launch({ args: ["--host-resolver-rules=MAP desk.test 127.0.0.1"] });
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await phone.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  const step = (m) => console.log("step:", m);
  await page.goto(`http://desk.test:${port}/`);
  await page.waitForSelector("#pair-device");
  step("pairing asks for a device name");
  await page.screenshot({ path: `${out}/phone-pair.png` });
  await page.fill("#pair-code", code);
  await page.fill("#pair-device", "phone");
  await page.click("button[type=submit]");
  try { await page.waitForSelector("#task", { timeout: 8000 }); } catch (e) { await page.screenshot({ path: `${out}/phone-stuck.png` }); console.log(await page.evaluate(() => document.body.innerText.slice(0, 600))); throw e; }
  step("paired as phone");
  await page.click("text=Add a folder");
  await page.fill("#add-path", `${root}/work`);
  await page.click("button:has-text('Use this folder')");
  await page.fill("#task", "The session list shows each session's first message. Make them easy to tell apart.");
  await page.click("button[aria-label='Start the task']");
  await page.waitForSelector(".ask-card .btn.accent", { timeout: 20000 });
  step("approval shown on the phone");
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/phone-approve.png` });
  const who = await page.textContent(".ask-card .fine");
  console.log("fine print:", who.includes("as phone") ? "names the phone" : who);
  await page.click(".ask-card .btn.accent");
  await page.waitForSelector(".step .result.ok", { timeout: 20000 });
  step("answered from the phone");
  // What the phone may not do.
  const refused = await page.evaluate(async () => {
    const r = await fetch("/pair", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ ticket: "x" }) });
    return r.status;
  });
  console.log("remote ticket status:", refused);
  await page.waitForTimeout(3000);
  const logs = fs.readdirSync(`${root}/data/nodwyn/sessions`).map((f) => fs.readFileSync(`${root}/data/nodwyn/sessions/${f}`, "utf8")).join("");
  console.log("log names the phone:", /"actor":"unix:uid=\d+,gid=\d+,pid=\d+ via web:phone"/.test(logs));
  const devices = fs.readFileSync(`${root}/config/nodwyn/devices.toml`, "utf8");
  console.log("devices.toml:", devices.split("\n").filter((l) => l.includes("name")).join(" "));
  console.log(execSync(`${process.env.NODWYN} devices`, { env }).toString().trim());
  console.log(errors.length ? "ERRORS\n" + errors.join("\n") : "no page errors");
  await browser.close();
})().catch((e) => { console.error("FAILED", e.message); process.exit(1); });
