// change-claims reads the lines a change adds to documents and to Go and
// Scheme comments, and says which of them state what nothing in the turn
// showed (ADR 32, amended 2026-10-15). In the deep study of commit-bench
// (2026-10-15) reviewers and analysts found 15 such claims in 36 candidate
// patches, none of which any harness rule read: the task's own account of a
// fuzz run ("40 s (9.4M executions) found nothing") copied into ADR 25 by
// three builds, one of them after the guard had refused the fuzz; "make
// validate passed with zero warnings" written before validate ran; amendment
// dates guessed; an ADR paragraph pasted twice by one edit; and 24 catalogue
// entries written from memory under models.dev's name. It names:
//
//   - a sentence that reports a run (passed, warnings, found nothing,
//     executions, a fuzz or a benchmark figure) when no run of the command it
//     names exited 0 in the turn, or none that did printed its figures;
//   - an amendment date the file did not have, when no command of the turn
//     printed it and the request does not give it;
//   - three or more lines a prose edit inserted that stand word for word
//     elsewhere in the file;
//   - a generated file (its head says Code generated or Generated by, or
//     names a "source" address; or the repository declares it) that the turn
//     edited by hand, when nothing ran its generator or named its source
//     after the last such edit.
//
// What the turn ran comes from the evidence loop, which keeps each command
// line, its exit status and the start and end of what it printed.

const claimsMax = 6

// claimRun is a command the turn ran, as the evidence loop kept it: its
// command line, its exit status (-1 when it did not run to an exit, or ran
// on the copy of the last commit), and what it printed.
type claimRun struct {
	line   string
	status int
	output string
}

// addedClaim is a line the change adds that states what nothing showed.
type addedClaim struct {
	path string
	line int // its line in the file now
	kind string
	text string
	why  string
}

// proseFile is a document the claims in it are read from: under docs/, or
// Markdown, LaTeX, reStructuredText, AsciiDoc or text anywhere.
func proseFile(rel string) bool {
	switch strings.ToLower(filepath.Ext(rel)) {
	case ".md", ".tex", ".rst", ".adoc", ".txt":
		return true
	}
	return strings.HasPrefix(rel, "docs/")
}

// commentMarker is the line comment of a code file whose comments are read,
// or "".
func commentMarker(rel string) string {
	switch strings.ToLower(filepath.Ext(rel)) {
	case ".go":
		return "//"
	case ".scm":
		return ";"
	}
	return ""
}

// addedBlock is a run of lines the change adds, as one text: the lines of a
// document, or of a code file's comments with their markers taken off.
type addedBlock struct {
	path  string
	first int      // the file's line number of the block's first line
	lines []string // the lines, markers taken off
}

// addedBlocks is the blocks of lines the change adds to rel, and the file's
// lines now.
func addedBlocks(rel string, old, cur []byte) ([]addedBlock, []string) {
	a, b := splitLines(string(old)), splitLines(string(cur))
	if len(a)+len(b) > withoutMaxLines {
		return nil, b
	}
	marker := commentMarker(rel)
	var blocks []addedBlock
	var open *addedBlock
	flush := func() {
		if open != nil && len(open.lines) > 0 {
			blocks = append(blocks, *open)
		}
		open = nil
	}
	for _, op := range myers(a, b) {
		if op.kind != '+' {
			if op.kind == ' ' {
				flush()
			}
			continue
		}
		text := op.line
		if marker != "" {
			t := strings.TrimSpace(text)
			if !strings.HasPrefix(t, marker) {
				flush()
				continue
			}
			text = strings.TrimSpace(strings.TrimLeft(t, marker))
		}
		if open == nil {
			open = &addedBlock{path: rel, first: op.bi + 1}
		}
		open.lines = append(open.lines, text)
	}
	flush()
	return blocks, b
}

// sentence is a sentence of a block and the line it starts on.
type sentence struct {
	text string
	line int
}

var sentenceEnd = regexp.MustCompile(`[.!?](\s|$)`)

// sentences splits a block at its sentences' ends; a blank line ends one
// too.
func (bl addedBlock) sentences() []sentence {
	var out []sentence
	var cur strings.Builder
	start := 0
	for i, l := range bl.lines {
		if strings.TrimSpace(l) == "" {
			if cur.Len() > 0 {
				out = append(out, sentence{cur.String(), bl.first + start})
				cur.Reset()
			}
			continue
		}
		rest := strings.TrimSpace(l)
		for rest != "" {
			if cur.Len() == 0 {
				start = i
			} else {
				cur.WriteByte(' ')
			}
			loc := sentenceEnd.FindStringIndex(rest)
			if loc == nil {
				cur.WriteString(rest)
				rest = ""
				continue
			}
			cur.WriteString(rest[:loc[0]+1])
			out = append(out, sentence{cur.String(), bl.first + start})
			cur.Reset()
			rest = strings.TrimSpace(rest[loc[1]:])
		}
	}
	if cur.Len() > 0 {
		out = append(out, sentence{cur.String(), bl.first + start})
	}
	return out
}

var (
	// caveatRE is a sentence that says something was not shown: a claim's
	// honest opposite.
	caveatRE = regexp.MustCompile(`(?i)\b(not (shown|run|verified|measured|checked|tested|reproduced)|unverified|unchecked|untested|did not run|was not run|could not (run|be run)|were not run|refused)\b`)
	// runWordRE is a word that reports how a run ended: in the past tense, or
	// "passes with" and the like, since "a test that passes on both" states a
	// rule rather than a run.
	runWordRE = regexp.MustCompile(`(?i:\b(passed|passes (with|here|now|on (the|this|your) change)|all pass|found (nothing|no)|(\d+|zero|no) warnings?|executions|execs)\b)|\bPASS\b`)
	// figureRE is a figure a run would print: a number with its unit.
	figureRE   = regexp.MustCompile(`(?i)(?:^|[^\w.])(\d+(?:\.\d+)?)\s*-?\s*([kmb]?)\s*(warnings?|executions?|execs|tests?|seconds?|second|sec|s|ms|minutes?|min|ns/op|%)(?:\W|$)`)
	zeroWarnRE = regexp.MustCompile(`(?i)\b(zero|no) warnings\b`)
)

var (
	fuzzWordRE     = regexp.MustCompile(`\bfuzz(ed|es|ing|er)?\b|\bexecs\b|\bexecutions\b`)
	benchWordRE    = regexp.MustCompile(`\bbenchmark(s|ed)?\b|\bns/op\b`)
	validateWordRE = regexp.MustCompile(`\bvalidate\b|\b\d+ warnings?\b`)
	testsPassRE    = regexp.MustCompile(`\b(tests?|suite)\b[^.;]{0,40}\b(passed|all pass|passes (with|here|now|on (the|this|your) change))\b`)
	testNamePassRE = regexp.MustCompile(`\b(Test[A-Z0-9_]\w*|test_\w+)\b[^.;]{0,40}\b(passed|passes (with|here|now|on (the|this|your) change))\b`)
)

// claimCommands is the commands a sentence that reports a run names, each as
// the key a run's command line holds; none for a sentence that reports no
// run. "test" stands for any test command.
func claimCommands(s string) []string {
	l := strings.ToLower(s)
	var keys []string
	switch {
	case fuzzWordRE.MatchString(l):
		return []string{"-fuzz"}
	case benchWordRE.MatchString(l) && figureRE.MatchString(s):
		return []string{"-bench"}
	case !runWordRE.MatchString(s):
		return nil
	}
	if strings.Contains(l, "make accept") {
		keys = append(keys, "make accept")
	}
	if validateWordRE.MatchString(l) || zeroWarnRE.MatchString(s) {
		keys = append(keys, "make validate")
	}
	if strings.Contains(l, "go test") {
		keys = append(keys, "go test")
	}
	if len(keys) == 0 && (testsPassRE.MatchString(l) || testNamePassRE.MatchString(s)) {
		keys = append(keys, "test")
	}
	return keys
}

// figure is a number a sentence gives, as a value.
type figure struct {
	text  string
	value float64
}

func figures(s string) []figure {
	var out []figure
	for _, m := range figureRE.FindAllStringSubmatch(s, -1) {
		v, err := strconv.ParseFloat(m[1], 64)
		if err != nil {
			continue
		}
		switch strings.ToLower(m[2]) {
		case "k":
			v *= 1e3
		case "m":
			v *= 1e6
		case "b":
			v *= 1e9
		}
		out = append(out, figure{strings.TrimSpace(m[1] + m[2] + " " + m[3]), v})
	}
	if zeroWarnRE.MatchString(s) {
		out = append(out, figure{"0 warnings", 0})
	}
	return out
}

var outputNumberRE = regexp.MustCompile(`\d+(?:\.\d+)?[kKmM]?`)

// summaryLines is how many of a run's last non-blank lines hold its result.
const summaryLines = 6

// lastLines is the last n non-blank lines of text, of a fuzz run's progress
// lines ("fuzz: elapsed: 12s, execs: 9289317 ...") the last only: they come
// every three seconds, and only the last count is the run's (A's
// 29.5M-execution run of 3422faf1 passed 9.3M at 12 s, while its ADR kept the
// task's 9.4M).
func lastLines(text string, n int) string {
	lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
	var out []string
	progress := false
	for i := len(lines) - 1; i >= 0 && len(out) < n; i-- {
		l := strings.TrimSpace(lines[i])
		if l == "" || strings.HasPrefix(l, "fuzz: elapsed:") && progress {
			continue
		}
		progress = progress || strings.HasPrefix(l, "fuzz: elapsed:")
		out = append(out, l)
	}
	return strings.Join(out, "\n")
}

// printed is whether output holds a number within 5% of f's value: a run's
// 29527198 execs is "29.5M executions", not "9.4M".
func printed(output string, f figure) bool {
	for _, n := range outputNumberRE.FindAllString(output, -1) {
		mult := 1.0
		switch n[len(n)-1] {
		case 'k', 'K':
			mult, n = 1e3, n[:len(n)-1]
		case 'm', 'M':
			mult, n = 1e6, n[:len(n)-1]
		}
		v, err := strconv.ParseFloat(n, 64)
		if err != nil {
			continue
		}
		v *= mult
		if v == f.value || f.value != 0 && math.Abs(v-f.value) <= 0.05*f.value {
			return true
		}
	}
	return false
}

// ranCommand is whether a run's command line is the command key names.
func ranCommand(line, key string) bool {
	l := strings.ToLower(line)
	switch key {
	case "-fuzz":
		return strings.Contains(l, "-fuzz") || strings.Contains(l, "fuzz")
	case "-bench":
		return strings.Contains(l, "-bench")
	case "test":
		for _, w := range []string{"test", "make validate", "make check", "make accept", "make ci"} {
			if strings.Contains(l, w) {
				return true
			}
		}
		return false
	}
	return strings.Contains(l, key)
}

// runClaim says why a sentence reporting a run is not backed by runs, or ""
// when they back it: each command it names has a run that exited 0, and each
// figure it gives is among the last lines one of those runs printed.
func runClaim(s string, runs []claimRun) string {
	keys := claimCommands(s)
	if len(keys) == 0 || caveatRE.MatchString(s) {
		return ""
	}
	var passing []claimRun
	for _, key := range keys {
		found := false
		for _, r := range runs {
			if r.status == 0 && ranCommand(r.line, key) {
				passing = append(passing, r)
				found = true
			}
		}
		if !found {
			name := strings.TrimPrefix(key, "-")
			if key == "test" {
				name = "a test"
			}
			return "no run of " + name + " of yours passed this turn"
		}
	}
	var missing []string
	for _, f := range figures(s) {
		shown := false
		for _, r := range passing {
			if printed(lastLines(r.output, summaryLines), f) {
				shown = true
				break
			}
		}
		if !shown {
			missing = append(missing, f.text)
		}
	}
	if len(missing) > 0 {
		return "no passing run of yours printed " + strings.Join(missing, ", ")
	}
	return ""
}

var (
	dateRE      = regexp.MustCompile(`\b(20\d\d)-(\d\d)-(\d\d)\b`)
	amendmentRE = regexp.MustCompile(`(?i)\bamend(ment|ed|s)?\b`)
)

// dateClaim is an amendment date a sentence adds and why it is not backed,
// or "", "":
// a date the file had at HEAD, or one a command printed or the request
// gives (as 2026-10-15 or 20261015, as in a session's name), is backed.
func dateClaim(s string, old []byte, request string, runs []claimRun) (string, string) {
	if !amendmentRE.MatchString(s) {
		return "", ""
	}
	for _, m := range dateRE.FindAllStringSubmatch(s, -1) {
		date, compact := m[0], m[1]+m[2]+m[3]
		if strings.Contains(string(old), date) || strings.Contains(request, date) || strings.Contains(request, compact) {
			continue
		}
		seen := false
		for _, r := range runs {
			if strings.Contains(r.output, date) || strings.Contains(r.output, compact) {
				seen = true
				break
			}
		}
		if !seen {
			return date, "no command of yours printed " + date + " and the request does not give it: run `date +%F`"
		}
	}
	return "", ""
}

// repeatLines is the minimum run of non-blank lines, and of characters in
// them, that a prose edit may not insert where it already stands.
const (
	repeatLines = 3
	repeatChars = 120
)

// repeatClaim is an added run of repeatLines non-blank lines, repeatChars
// characters or more, that stands word for word elsewhere in the file: the
// line it starts on and the line of the other copy, or 0, 0. On 5040f9fe
// one fs-edit whose new text re-typed the amendment before its anchor put
// that amendment in ADR 9 twice, and the tool's answer showed it.
func repeatClaim(start, end int, lines []string) (int, int) {
	for i := start; i+repeatLines <= end; i++ {
		window := lines[i : i+repeatLines]
		size := 0
		blank := false
		for _, l := range window {
			if strings.TrimSpace(l) == "" {
				blank = true
			}
			size += len(strings.TrimSpace(l))
		}
		if blank || size < repeatChars {
			continue
		}
		for j := 0; j+repeatLines <= len(lines); j++ {
			if j+repeatLines > start && j < end {
				continue // inside the inserted run itself
			}
			same := true
			for k := range repeatLines {
				if lines[j+k] != window[k] {
					same = false
					break
				}
			}
			if same {
				return i + 1, j + 1
			}
		}
	}
	return 0, 0
}

var (
	generatedRE = regexp.MustCompile(`(?i)\b(?:code )?generated by ([^\s;,.]+(?:\.[a-z]+)?)|\bcode generated\b.*\bdo not edit\b`)
	sourceRE    = regexp.MustCompile(`"source"\s*:\s*"(https?://[^"]+)"|(?m)^source:\s*(https?://\S+)`)
)

// generatedBy is what a file's head says makes it: its generator, or the
// address its data comes from, or "" for a file nobody generates.
func generatedBy(head []byte) (generator, source string) {
	if len(head) > 2048 {
		head = head[:2048]
	}
	if m := sourceRE.FindSubmatch(head); m != nil {
		source = string(m[1]) + string(m[2])
	}
	if m := generatedRE.FindSubmatch(head); m != nil {
		generator = string(m[1])
		if generator == "" {
			generator = "go generate"
		}
	}
	return generator, source
}

// generatedClaim says why a hand edit of a generated file stands on nothing,
// or "": a command after the last edit that names its generator (or go
// generate) or its source address or host backs it.
func generatedClaim(generator, source string, after []string) string {
	keys := []string{"go generate"}
	if generator != "" {
		keys = append(keys, generator, filepath.Base(generator))
	}
	if source != "" {
		keys = append(keys, source)
		if host := strings.SplitN(strings.TrimPrefix(strings.TrimPrefix(source, "https://"), "http://"), "/", 2)[0]; host != "" {
			keys = append(keys, host)
		}
	}
	for _, cmd := range after {
		for _, k := range keys {
			if k != "" && strings.Contains(cmd, k) {
				return ""
			}
		}
	}
	what := "is generated by " + generator
	if source != "" {
		what = "says its data comes from " + source
	}
	return what + ", and nothing ran its generator or read its source after you edited it"
}

// changeClaims is the lines the change adds that state what nothing showed,
// in path and line order, at most claimsMax. runs are the turn's commands;
// edits the files it edited by hand, each with the commands run after its
// last edit; declared the generated files the repository declares, with the
// command that makes each.
func changeClaims(c changeFiles, request string, runs []claimRun, edits map[string][]string, declared map[string]string) []addedClaim {
	var out []addedClaim
	dated := map[string]bool{} // a date is named once, where it first stands
	for _, rel := range c.paths {
		cur, ok := c.now(rel)
		if !ok {
			continue
		}
		old, _ := c.head(rel)
		if after, edited := edits[rel]; edited {
			generator, source := generatedBy(cur)
			if cmd, ok := declared[rel]; ok {
				generator = cmd
			}
			if generator != "" || source != "" {
				if why := generatedClaim(generator, source, after); why != "" {
					out = append(out, addedClaim{path: rel, line: 1, kind: "generated", why: why})
				}
			}
		}
		if !proseFile(rel) && commentMarker(rel) == "" {
			continue
		}
		blocks, lines := addedBlocks(rel, old, cur)
		for _, bl := range blocks {
			if proseFile(rel) && commentMarker(rel) == "" {
				if at, from := repeatClaim(bl.first-1, bl.first-1+len(bl.lines), lines); at > 0 {
					out = append(out, addedClaim{path: rel, line: at, kind: "repeat",
						text: strings.TrimSpace(lines[at-1]),
						why:  fmt.Sprintf("lines %d-%d repeat lines %d-%d word for word: if your edit re-typed text before the text it replaced, it is now in the file twice", at, at+repeatLines-1, from, from+repeatLines-1)})
				}
			}
			for _, s := range bl.sentences() {
				if why := runClaim(s.text, runs); why != "" {
					out = append(out, addedClaim{path: rel, line: s.line, kind: "run", text: s.text, why: why})
				}
				if date, why := dateClaim(s.text, old, request, runs); why != "" && !dated[date] {
					dated[date] = true
					out = append(out, addedClaim{path: rel, line: s.line, kind: "date", text: s.text, why: why})
				}
			}
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].path != out[j].path {
			return out[i].path < out[j].path
		}
		return out[i].line < out[j].line
	})
	if len(out) > claimsMax {
		out = out[:claimsMax]
	}
	return out
}

func changeClaimsPrim(o Options) *scheme.Prim {
	return &scheme.Prim{
		Name: "change-claims",
		Meta: scheme.Meta{
			Doc: "The lines the uncommitted change adds to documents (under docs/, or .md, .tex, .rst, .adoc, .txt) and to Go and Scheme comments that state what nothing in the turn showed, at most " + fmt.Sprint(claimsMax) + ", as a list of alists of path, line (now), kind, text and why. Kinds: run, a sentence that reports a run (passed, warnings, found nothing, executions, a fuzz or benchmark figure) when no run of the command it names exited 0, or none that did printed its figures (within 5%); date, an amendment date the file did not have that no run printed and request does not give; repeat, three or more non-blank lines (120 characters or more) a document's edit inserted that stand word for word elsewhere in it; generated, a file whose head says Code generated or Generated by, or names a \"source\" address, or that declared names, edited by hand with no command after the last edit naming its generator, go generate, or its source. runs is the turn's commands, each a list of its command line, its exit status (#f when it did not run to an exit or ran on the copy of the last commit) and what it printed; edits an alist of each path edited by hand and the command lines run after its last edit; declared a list of (path command) rows. Hidden; registered in a git work tree (ADR 32, amended 2026-10-15).",
			Params: []scheme.Param{
				{Name: "request", Type: "string", Doc: "the request: a date it gives is backed"},
				{Name: "runs", Type: "list", Doc: "the turn's commands: (line status output)"},
				{Name: "edits", Type: "list", Doc: "(path . command-lines) for each file edited by hand"},
				{Name: "declared", Type: "list", Doc: "(path command) for each generated file the repository declares"},
			},
			Host:   true,
			Hidden: true,
		},
		Handler: func(c *scheme.Call) (scheme.Value, error) {
			request, err := c.String(0)
			if err != nil {
				return scheme.Value{}, err
			}
			items, err := c.List(1)
			if err != nil {
				return scheme.Value{}, err
			}
			var runs []claimRun
			for _, it := range items {
				row, _ := it.Slice()
				if len(row) != 3 || row[0].Kind != scheme.KString || row[2].Kind != scheme.KString {
					continue
				}
				status := -1
				if row[1].Kind == scheme.KInt {
					status = int(row[1].I)
				}
				runs = append(runs, claimRun{line: row[0].S, status: status, output: row[2].S})
			}
			pairs, err := c.List(2)
			if err != nil {
				return scheme.Value{}, err
			}
			edits := map[string][]string{}
			for _, it := range pairs {
				if it.Kind != scheme.KPair || it.P.Car.Kind != scheme.KString {
					continue
				}
				var after []string
				cmds, _ := it.P.Cdr.Slice()
				for _, cmd := range cmds {
					if cmd.Kind == scheme.KString {
						after = append(after, cmd.S)
					}
				}
				edits[strings.TrimPrefix(it.P.Car.S, "./")] = after
			}
			rows, err := c.List(3)
			if err != nil {
				return scheme.Value{}, err
			}
			declared := map[string]string{}
			for _, it := range rows {
				row, _ := it.Slice()
				if len(row) == 2 && row[0].Kind == scheme.KString && row[1].Kind == scheme.KString {
					declared[row[0].S] = row[1].S
				}
			}
			ch, err := workChange(c.Ctx, o)
			if err != nil {
				return scheme.Value{}, fmt.Errorf("change-claims: %w", err)
			}
			var out []scheme.Value
			for _, cl := range changeClaims(ch, request, runs, edits, declared) {
				out = append(out, scheme.List(
					scheme.Cons(scheme.Str("path"), scheme.Str(cl.path)),
					scheme.Cons(scheme.Str("line"), scheme.Int(int64(cl.line))),
					scheme.Cons(scheme.Str("kind"), scheme.Str(cl.kind)),
					scheme.Cons(scheme.Str("text"), scheme.Str(cl.text)),
					scheme.Cons(scheme.Str("why"), scheme.Str(cl.why))))
			}
			return scheme.List(out...), nil
		},
	}
}
